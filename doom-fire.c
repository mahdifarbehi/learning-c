#include <stdio.h>
#include <stdlib.h>
#include <time.h>
#include <unistd.h>
#include <signal.h>

volatile sig_atomic_t running = 1;

#define WIDTH 250
#define HEIGHT 60

int palette[37][3] = {
    {0x07,0x07,0x07},{0x1F,0x07,0x07},{0x2F,0x0F,0x07},{0x47,0x0F,0x07},
    {0x57,0x17,0x07},{0x67,0x1F,0x07},{0x77,0x1F,0x07},{0x8F,0x27,0x07},
    {0x9F,0x2F,0x07},{0xAF,0x3F,0x07},{0xBF,0x47,0x07},{0xC7,0x47,0x07},
    {0xDF,0x4F,0x07},{0xDF,0x57,0x07},{0xDF,0x57,0x07},{0xD7,0x5F,0x07},
    {0xD7,0x5F,0x07},{0xD7,0x67,0x0F},{0xCF,0x6F,0x0F},{0xCF,0x77,0x0F},
    {0xCF,0x7F,0x0F},{0xCF,0x87,0x17},{0xC7,0x87,0x17},{0xC7,0x8F,0x17},
    {0xC7,0x97,0x1F},{0xBF,0x9F,0x1F},{0xBF,0x9F,0x1F},{0xBF,0xA7,0x27},
    {0xBF,0xA7,0x27},{0xBF,0xAF,0x2F},{0xB7,0xAF,0x2F},{0xB7,0xB7,0x2F},
    {0xB7,0xB7,0x37},{0xCF,0xCF,0x6F},{0xDF,0xDF,0x9F},{0xEF,0xEF,0xC7},
    {0xFF,0xFF,0xFF}
};

void printColor(int num){
    printf("\x1b[48;2;%d;%d;%dm  ", palette[num][0], palette[num][1], palette[num][2]);
    printf("\x1b[0m");
}

void stop(int sig){
    (void)sig;
    running = 0;
}

int main(void) {
    signal(SIGINT, stop);

    srand(time(NULL));
    int cells[WIDTH * HEIGHT] = {0};
    
    for (int c = 0; c < WIDTH; c++){
        cells[(HEIGHT-1) * WIDTH + c] = 36;
    }

    printf("\x1b[?25l");

    while(running){
        printf("\x1b[H");
        for (int r = 0; r < HEIGHT-1; r++){
            for (int c = 0; c < WIDTH; c++){
                int offset = (rand() % 3) - 1;
                int src = c + offset;
                if (src < 0) src = 0;
                if (src >= WIDTH) src = WIDTH - 1;
    
                int below = cells[(r + 1) * WIDTH + c];
                int v = below - (rand() % 3);
                if (v < 0) v = 0;
                cells[r * WIDTH + src] = v;
            }
        }
        for (int r = 0; r < HEIGHT; r++){
            for (int c = 0; c < WIDTH; c++){
                printColor(cells[r * WIDTH + c]);
            }
            printf("\n");
        }
        usleep(50000);
    }

    printf("\x1b[0m\x1b[?25h\n");
    return 0;
}